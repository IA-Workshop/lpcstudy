def verdicts(results: dict, config: StudyConfig) -> dict:
    """Aggregate per-system verdicts into supported / not supported / inconclusive (v3 section 7).

    Each system's verdict for a criterion is the string ``results[s][key]["verdict"]`` (pass,
    fail or inconclusive), never a boolean, so that an inconclusive result cannot read as a
    failure. The overall verdict is ``statistics.overall_verdict`` over the three v3 systems
    (DEC-0016 O1): supported only if all three pass, not supported if any present system fails,
    inconclusive otherwise, with the missing systems listed. A one-system run (smoke) can
    therefore never read "supported". Verdicts are not conditioned on ``gate_pass``: a gate
    failure marks that system's results provisional (v3 section 6 E0), which the markdown shows
    next to the gate line. The Q-N row is read, not decided; the gain-bound row is reported
    with no pass/fail bar (v3 section 2).

    Parameters
    ----------
    results : dict
        Study results.
    config : StudyConfig
        Configuration (core systems).

    Returns
    -------
    dict
        Result key of each table row that has a result to ``by_system`` (the verdict string of
        each system), ``verdict`` and, for a decided row, ``missing_systems``. A row with no
        result in any system is absent; a row with a result in some systems only raises
        ``KeyError``.

    Raises
    ------
    ValueError
        If a system's results carry a hypothesis-shaped key that is not in the identifier table
        (results written before WU-0002.2), or a decided row has no valid ``verdict`` (results
        written before WU-0002.9, which stored a boolean ``pass``): nothing is relabelled. Also if
        a system is not one of the three v3 systems.
    """
    out = {}
    systems = [s for s in config.core_systems if s in results["systems"]]
    for s in systems:  # before any flag is read: a pre-v3 results file must not be relabelled
        try:
            check_keys(results["systems"][s])
        except ValueError as stale:
            raise ValueError(f"results of system {s} use identifiers of a schema older than "
                             f"WU-0002.2 (v1 keys); regenerate them with a new run: {stale}"
                             ) from None
    for row in HYPOTHESIS_TABLE:
        if not any(row.key in results["systems"][s] for s in systems):
            continue  # no result in any system; write_markdown lists the row
        if row.role == "estimate":  # Q-N: an estimate is read, not passed (v3 section 7)
            readings = {s: _qn_primary_reading(results["systems"][s][row.key])
                        for s in systems}
            out[row.key] = {"by_system": readings, "verdict": "estimate (read, no pass/fail)"}
            continue
        if row.role == "reported":  # the gain bound has no bar (v3 section 2)
            for s in systems:
                results["systems"][s][row.key]  # a result missing in one system raises KeyError
            out[row.key] = {"by_system": {s: "reported" for s in systems},
                            "verdict": REPORTED_VERDICT}
            continue
        found = {s: results["systems"][s][row.key].get("verdict") for s in systems}
        stale = [s for s, v in found.items() if v not in FLAGS]
        if stale:
            raise ValueError(f"result {row.key} of system(s) {stale} has no verdict (pass, fail "
                             "or inconclusive): written before WU-0002.9; regenerate it with a "
                             "new run")
        overall, missing = overall_verdict(found)
        out[row.key] = {"by_system": found, "verdict": overall, "missing_systems": missing}
    return out


def _fmt(value: float, digits: int = 3) -> str:
    return "n/a" if value is None or (isinstance(value, float) and np.isnan(value)) \
        else f"{value:.{digits}g}"


def _interval(ci: list | None, digits: int = 3) -> str:
    """``[lo, hi]`` of a stored interval, or ``n/a`` when the statistic could not be computed."""
    return "n/a" if ci is None else f"[{_fmt(ci[0], digits)}, {_fmt(ci[1], digits)}]"


def _verdict_text(res: dict) -> str:
    """The three-valued verdict of a result, with the reason when it is inconclusive."""
    reason = f" ({res['reason']})" if res.get("reason") else ""
    return f"{res['verdict']}{reason}"


def _key_number(key: str, res: dict) -> str:
    """One-line numeric summary of a result (by its table key) for one system."""
    r = res[key]
    match key:
        case "H1a":
            parts = [f"rho={k}: 1/d (n_lib fit)={_fmt(v['fitted_inverse_dim'])}, "
                     f"ratio {_fmt(v['ratio'])} [{_fmt(v['ratio_ci'][0])}, "
                     f"{_fmt(v['ratio_ci'][1])}] {_verdict_text(v)}"
                     for k, v in r["by_noise"].items()]
            return "; ".join(parts) + f" (1/d_LB={_fmt(r['inverse_dim_reference'])})"
        case "H1b":
            return f"CP {_fmt(r['CP']['slope'])}, PLP {_fmt(r['PLP']['slope'])} " \
                   f"[{_fmt(r['PLP']['ci'][0])}, {_fmt(r['PLP']['ci'][1])}]: {_verdict_text(r)}"
        case "H1c":
            plp, cp = r["PLP"], r["CP"]
            return f"PLP {_fmt(plp.get('median_ratio'))} {_interval(plp.get('ci'))}: " \
                   f"{_verdict_text(r)}; CP {_fmt(cp.get('median_ratio'))} " \
                   f"{_interval(cp.get('ci'))} (reported, no verdict)"
        case "H1d":
            s = {name: row["spearman"] for name, row in r["rows"].items()}
            return f"eps {_fmt(s['analog_seed'], 2)}, delta {_fmt(s['estimation_seed'], 2)}, " \
                   f"Lambda {_fmt(s['growth'], 2)}, N {_fmt(s['nhat'], 2)}: {_verdict_text(r)}"
        case "Q-N":
            def block(profile: str, target: str) -> str:
                d = r[profile][target]
                return (f"{d['reading']} (dR2 {_fmt(d['delta_r2'], 2)} "
                        f"[{_fmt(d['ci'][0], 2)}, {_fmt(d['ci'][1], 2)}])" if "reading" in d else
                        f"dR2 {_fmt(d['delta_r2'], 2)} "
                        f"[{_fmt(d['ci'][0], 2)}, {_fmt(d['ci'][1], 2)}]")
            return (f"{r['primary']}: interior {block(r['primary'], 'logit_w_interior')}, "
                    f"w*=0 {block(r['primary'], 'w_zero_indicator')}, "
                    f"log T {block(r['primary'], 'log_horizon')}; "
                    f"deployable interior {r['deployable']['logit_w_interior']['reading']}, "
                    f"w*=0 {r['deployable']['w_zero_indicator']['reading']} "
                    f"(w*=0: {r['n_w_zero']}, w*=1: {r['n_w_one']})")
        case "H2a":
            two = r["part_ii"]
            return f"(i) {r['part_i_verdict']}: range {_fmt(r['median_range'])} " \
                   f"(CI hi {_fmt(r['range_ci'][1])}, n={r['n_eligible_states']}); " \
                   f"(ii) {r['part_ii_verdict']}: partial r zero " \
                   f"{_fmt(two['zero']['partial_corr'], 2)} " \
                   f"[{_fmt(two['zero']['ci'][0], 2)}, {_fmt(two['zero']['ci'][1], 2)}], " \
                   f"interior {_fmt(two['interior']['partial_corr'], 2)} " \
                   f"[{_fmt(two['interior']['ci'][0], 2)}, {_fmt(two['interior']['ci'][1], 2)}] " \
                   f"(w*=0: {r['n_w_zero']}, w*=1: {r['n_w_one']})"
        case "H2b":
            change = r["library_change"]
            return f"rho rank corr {_fmt(r['noise']['mean_state_spearman'], 2)}; " \
                   f"n_lib 10^3->10^4 change {_fmt(change['mean_change'], 2)} " \
                   f"{_interval(change['ci'], 2)}: {_verdict_text(r)}"
        case "H2c":
            best = f"A4_minus_{r['best_single']}"
            part = lambda p: f"{_fmt(p['mean'], 3)} {_interval(p['ci'])} " \
                             f"({_fmt(100 * p['relative'], 3)}%) {_verdict_text(p)}"
            return f"A4-A2 {part(r['A4_minus_A2'])}; A4-{r['best_single']} {part(r[best])}; " \
                   f"A4o-A2 {_fmt(100 * r['A4o_minus_A2']['relative'], 3)}% (reported): " \
                   f"{_verdict_text(r)}"
        case "H2d":
            return f"A4/A3-1 = {_fmt(100 * r['in_distribution_excess'], 3)}% " \
                   f"[{_fmt(100 * r['ci'][0], 3)}, {_fmt(100 * r['ci'][1], 3)}]%: " \
                   f"{_verdict_text(r)}"
        case "gain_bound":
            out = r["n_screened_out"]  # a result without the counts fails loudly (PRIME.4)
            screens = (f" of {r['n_total_states']}; screened out: "
                       f"growth<=0 {out['growth_nonpositive']}, "
                       f"censored {out['censored_single_forecaster']}, "
                       f"covariance<0 {out['negative_covariance']}")
            return f"within bound {_fmt(r['fraction_within_bound'], 3)} " \
                   f"(n={r['n_states']}{screens}, max gain {_fmt(r['max_gain_lyapunov'], 2)} LT)"
