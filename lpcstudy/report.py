def _lyapunov_lines(results: dict, systems: list[str]) -> list[str]:
    """Markdown of the subsection comparing lambda_max with published values (WU-0007.3).

    The code's value is read from ``systems.<s>.context.lambda_max``; the references and
    tolerances are the constants above. A system without that value shows "n/a", not a skip. The
    comparison is report-only: it does not enter the validation gate or any verdict.
    """
    lines = ["| System | Code λ_max | Published | Source | Relative difference | Result |",
             "|---|---|---|---|---|---|"]
    for s in systems:
        found = results["systems"][s].get("context", {}).get("lambda_max")
        code = "n/a" if found is None else _fmt(found, 6)
        references = LYAPUNOV_REFERENCES[s]  # a system without an entry raises (PRIME.4)
        if not references:
            lines.append(f"| {s} | {code} | none | no confirmed published value | n/a | "
                         "not validated: no published reference at these parameters "
                         "(known limitation, NVVUQ.13, DEC-0010) |")
        for value, tolerance, source in references:
            if found is None:
                gap, verdict = "n/a", "n/a: no λ_max in the results"
            else:
                relative = found / value - 1.0
                gap = f"{100 * relative:+.2f}%"
                verdict = (f"PASS: within {100 * tolerance:g}%" if abs(relative) <= tolerance
                           else f"FAIL: outside {100 * tolerance:g}%; step size suspected "
                                "(LPC.NV.1), reported, not tuned")
            lines.append(f"| {s} | {code} | {_fmt(value, 4)} | {source} | {gap} | {verdict} |")
    value, tolerance, source = LYAPUNOV_MEMO
    lines.append(f"| chua, memo parameter set (α=9, β=100/7, m0=−8/7, m1=−5/7) | not computed "
                 f"in this run | {_fmt(value, 4)} | {source} | n/a | "
                 f"within {100 * tolerance:g}% is asserted by `{LYAPUNOV_MEMO_TEST}`; "
                 "a different parameter set from the study's: validates the routine and the "
                 "field form, not the study's Chua parameters |")
    lines += ["",
              "Every quantity is defined for the fixed-step RK4 flow map at the configured "
              "observation interval, not for the continuous ODE (LPC.NV.1). λ_max is estimated "
              "on that map by Benettin's method and compared in natural time units with "
              "published values for the continuous systems.", "",
              "Chua at the study's own parameters (α=15.6, β=28, m0=−1.143, m1=−0.714) has no "
              "confirmed published value (known limitation, NVVUQ.13, DEC-0010): its λ_max is "
              "reported but not validated.", "",
              "Validation against a real-world referent does not apply: the three systems are "
              "mathematical models (NVVUQ.13).", "",
              "This comparison is report-only: it does not enter the validation gate or any "
              "verdict."]
    return lines


def _p2c_lines(results: dict, systems: list[str]) -> list[str]:
    """Markdown of the Theorem P2(c) verification subsection (WU-0005.5).

    One row per system, read from ``systems.<s>.verification.P2c``; a system without the block
    shows "n/a", not a skip. The check is report-only: it carries no verdict and is not part of
    the validation gate or of any verdict. A violation is shown as a defect, never as a flag on
    the results.
    """
    lines = ["| System | States | Violations | Chain violations (N≤A, A≤B, P2(a), triangle, "
             "consistency) | Switching states | States with B = 0 | N/√B (median, p90, max) | "
             "Same draws as N |", "|---|---|---|---|---|---|---|---|"]
    for s in systems:
        block = results["systems"][s].get("verification", {}).get("P2c")
        if block is None:
            lines.append(f"| {s} | n/a: no P2(c) result | | | | | | |")
            continue
        chain = block["n_chain_violations"]
        spread = block["tightness"]["N_over_sqrt_B"]
        tight = "n/a" if spread["median"] is None else \
            f"{_fmt(spread['median'], 3)}, {_fmt(spread['p90'], 3)}, {_fmt(spread['max'], 3)}"
        found = block["n_violations"]
        lines.append(
            f"| {s} | {block['n_states']} | "
            + (f"{found}" if not found else f"**{found}: DEFECT**")
            + f" | {chain['N_le_A']}, {chain['A_le_B']}, {chain['p2a']}, {chain['triangle']}, "
            f"{chain['consistency']} | {block['n_switching_states']} | "
            f"{block['n_zero_bound_states']} | {tight} | "
            + ("not compared" if block["same_draws_identical"] is None
               else ("yes" if block["same_draws_identical"] else "**NO: DEFECT**")) + " |")
    lines += ["",
              "Verification check (NVVUQ.14, v3 Theorem P2(c)); not a hypothesis test; no "
              "verdict; not in the validation gate. At the core cell (k = 1) and on the same "
              "oracle draws as N, every state must satisfy N² ≤ A ≤ B, where "
              "A = mean ‖Y_r − X₁‖² / (ρ²D) is the spread of the retrieved analogs Y_r about "
              "the clean-query analog X₁ and B = 4 mean (r₁ + ‖η_r‖)² 1{‖η_r‖ ≥ Δ/2} / (ρ²D) "
              "is the bound, both over the M draws, in the units of N². This holds exactly, so a "
              "violation is a code defect, not sampling noise; the slack is the round-off "
              "bound of the check (κ = 1e-13, τ_N), not a tolerance fitted to results. "
              "N/√B near 0 means the bound is loose for that state."]
    return lines


def write_markdown(results: dict, config: StudyConfig, path: Path) -> None:
    """Write the human-readable results report.

    Parameters
    ----------
    results : dict
        Study results.
    config : StudyConfig
        Configuration.
    path : Path
        Output file.
    """
    systems = [s for s in config.core_systems if s in results["systems"]]
    lines = [f"# Results — preset `{config.name}`", "",
             *header_lines(results.get("provenance")), "",
             INTRO, "",
             "## Hypothesis verdicts", "",
             "| ID | Hypothesis | " + " | ".join(systems) + " | Verdict |",
             "|---|---|" + "---|" * len(systems) + "---|"]
    gate = {s: results["systems"][s]["validation"].get("gate", {}).get("gate_pass")
            for s in systems}
    gate_lines = ["", "Validation gate: " + ", ".join(
        f"{s} {'PASS' if g else 'FAIL (results provisional)' if g is not None else 'n/a'}"
        for s, g in gate.items())]
    if config.name == "smoke":
        gate_lines += ["", SMOKE_GATE_NOTE]
    lines[lines.index("## Hypothesis verdicts") + 1:lines.index("## Hypothesis verdicts") + 1] = \
        gate_lines
    ver = results["verdicts"]
    for row in HYPOTHESIS_TABLE:
        if row.key not in ver:  # a table row without a result is listed, not dropped
            cells = ["n/a: no result" for _ in systems]
            lines.append(f"| {row.v3_id} | {_hypothesis_text(row, computed=False)} | "
                         + " | ".join(cells) + " | no result |")
            continue
        cells = []
        for s in systems:
            if row.role == "estimate":
                cells.append(f"{ver[row.key]['by_system'][s]}: "
                             f"{_key_number(row.key, results['systems'][s])}")
                continue
            if row.role == "reported":  # no bar, so no flag
                cells.append(_key_number(row.key, results["systems"][s]))
                continue
            flag = FLAGS[ver[row.key]["by_system"][s]]
            cells.append(f"{flag}: {_key_number(row.key, results['systems'][s])}")
        missing = ver[row.key].get("missing_systems")
        overall = ver[row.key]["verdict"] + (f" (missing: {', '.join(missing)})" if missing else "")
        lines.append(f"| {row.v3_id} | {HYPOTHESES[row.key]} | " + " | ".join(cells)
                     + f" | {overall} |")
    # --- WU-0008.3 begin ---
    lines += interval_label_lines(results, systems, config)
    # --- WU-0008.3 end ---
    # --- WU-0008.4 begin ---
    lines += ["", *qoi_declaration_lines(config)]
    # --- WU-0008.4 end ---

    lines += ["", "## Allocation rules at the core cell (test split)", ""]
    for s in systems:
        sc = results["systems"][s]["scores"]
        horizons = list(next(iter(sc.values()))["mse"])
        lines += [f"### {s}", "", "| Rule | " + " | ".join(f"MSE {h}" for h in horizons) +
                  " | regret H_ref | agreement | KM median (LT) | RMST (LT) |",
                  "|---|" + "---|" * (len(horizons) + 4)]
        for rule, v in sc.items():
            lines.append(f"| {rule} {RULE_LABELS[rule]} | " +
                         " | ".join(_fmt(x, 3) for x in v["mse"].values()) +
                         f" | {_fmt(v['regret'][horizons[2]], 3)} | "
                         f"{_fmt(v['agreement_href'], 3)} | {_fmt(v['km_median_lyapunov'], 3)} | "
                         f"{_fmt(v['rmst_lyapunov'], 3)} |")
        rec = results["systems"][s]["oracle_recovery"]
        lines += ["", f"Oracle recovery: A4 recovers {_fmt(100 * rec['A4_vs_A4o'], 3)}% of the "
                  f"oracle-seed closed form's gain over A2; A5 recovers "
                  f"{_fmt(100 * rec['A5_vs_Astar'], 3)}% of A*'s.", ""]

    lines += ["## Validation gate", "", "| Check | Criterion | " + " | ".join(systems) + " |",
              "|---|---|" + "---|" * len(systems)]
    for key, (label, criterion, ok) in VALIDATION_CRITERIA.items():
        cells = []
        for s in systems:
            val = results["systems"][s]["validation"]
            value = val["convergence"][str(config.n_oracle_draws)]["median_half_width"] \
                if key == "convergence" else val[key]
            flag = "" if ok is None else (" PASS" if ok(value) else " FAIL")
            cells.append(_fmt(value, 3) + flag)
        lines.append(f"| {label} | {criterion} | " + " | ".join(cells) + " |")
    lines += _v7_rows(results, systems, config)
    # --- WU-0008.3 begin ---
    lines += ["", v4_label_line(config)]
    # --- WU-0008.3 end ---
    lines += ["", "### Largest Lyapunov exponent against published values", "",
              *_lyapunov_lines(results, systems)]
    lines += ["", "### Theorem P2(c) bound (verification check, not a hypothesis)", "",
              *_p2c_lines(results, systems)]
    # --- WU-0008.1 begin ---
    lines += ["", *budget_lines(results, systems, config)]
    # --- WU-0008.1 end ---

    if "robustness" in results:
        lines += ["", "## Robustness (core cell)", ""]
        for s, variants in results["robustness"].items():
            lines += [f"### {s}", "", "| Variant | H2a range | H2a partial r (w*=0) | "
                      "H2a partial r (interior) | A4 vs A2 | A4/A3 | A5 regret | H1b CP | "
                      "H1b PLP |", "|---|---|---|---|---|---|---|---|---|"]
            for label, v in variants.items():
                if "error" in v:
                    lines.append(f"| {label} | error: {v['error']} | | | | | | | |")
                elif "H2a_partial_corr_zero_fin" in v:
                    lines.append(f"| {label} | | {_fmt(v['H2a_partial_corr_zero_fin'], 2)} | "
                                 f"{_fmt(v['H2a_partial_corr_interior_fin'], 2)} | | | | | "
                                 f"corr(fin, lin) {_fmt(v['corr_fin_vs_linear'], 2)} |")
                else:
                    lines.append(
                        f"| {label} | {_fmt(v['H2a_median_range'], 3)} | "
                        f"{_fmt(v['H2a_partial_corr_zero'], 2)} | "
                        f"{_fmt(v['H2a_partial_corr_interior'], 2)} | "
                        f"{_fmt(100 * v['A4_vs_A2_relative'], 3)}% | {_fmt(v['A4_over_A3'], 3)} | "
                        f"{_fmt(100 * v['A5_regret_ratio'], 3)}% | "
                        f"{_fmt(v['H1b']['CP']['slope'], 3)} | {_fmt(v['H1b']['PLP']['slope'], 3)} |")

    # --- WU-0008.3 begin ---
    lines += ["", *figure_caption_lines(config)]
    # --- WU-0008.3 end ---
    lines += ["", *handling_lines(results, systems)]  # WU-0002.11b: Handling section
    path.write_text("\n".join(lines) + "\n")


def _style(ax: plt.Axes) -> None:
    ax.grid(True, color=GRID, linewidth=0.8)
    ax.set_axisbelow(True)
    for side in ("top", "right"):
        ax.spines[side].set_visible(False)
    for side in ("left", "bottom"):
        ax.spines[side].set_color(INK_2)
    ax.tick_params(colors=INK_2, labelsize=8)
    ax.xaxis.label.set_color(INK)
    ax.yaxis.label.set_color(INK)
    ax.title.set_color(INK)


